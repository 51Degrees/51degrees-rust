//! What the 51Did cloud engine logs when the cloud request fails. Kept in its
//! own test binary because a logger is installed once for the whole process.

use std::sync::{Arc, Mutex};

use fiftyone_cloud_request_engine::{
    CloudHttpClient, CloudHttpRequest, CloudHttpResponse, CloudRequestEngine,
};
use fiftyone_fodid_cloud::FodIdCloudEngine;
use fiftyone_pipeline_core::{Evidence, Pipeline};

/// Records from the 51Did and request engines at info level or above, each
/// as its target and "LEVEL message".
static LOGGED: Mutex<Vec<(String, String)>> = Mutex::new(Vec::new());

struct TestLogger;

impl log::Log for TestLogger {
    fn enabled(&self, metadata: &log::Metadata) -> bool {
        let target = metadata.target();
        metadata.level() <= log::Level::Info
            && (target.starts_with("fiftyone_fodid_cloud")
                || target.starts_with("fiftyone_cloud_request_engine"))
    }

    fn log(&self, record: &log::Record) {
        if self.enabled(record.metadata()) {
            LOGGED.lock().unwrap().push((
                record.target().to_owned(),
                format!("{} {}", record.level(), record.args()),
            ));
        }
    }

    fn flush(&self) {}
}

static LOGGER: TestLogger = TestLogger;

/// A cloud granting the 51Did product whose data endpoint fails, as in a
/// cloud outage.
struct DataDownCloud;

impl CloudHttpClient for DataDownCloud {
    fn send(&self, request: &CloudHttpRequest) -> Result<CloudHttpResponse, String> {
        let (status, body) = if request.url.contains("accessibleproperties") {
            (
                200,
                r#"{"Products":{"fodid":{"DataTier":"CloudV4","Properties":[
                    {"Name":"IdProbGlobal","Type":"String","Category":"Identifier"}]}}}"#,
            )
        } else if request.url.contains("evidencekeys") {
            (200, r#"["header.user-agent"]"#)
        } else {
            (500, r#"{"errors":["the service failed"]}"#)
        };
        Ok(CloudHttpResponse {
            status,
            body: body.to_owned(),
            retry_after: None,
        })
    }
}

/// The line that says the 51Did engine did not process is logged under the
/// engine's own module, as .NET logs it through the engine's own logger, so
/// a log filter on this crate shows it.
#[test]
fn a_failed_request_logs_that_the_51did_engine_did_not_process() {
    let _ = log::set_logger(&LOGGER);
    log::set_max_level(log::LevelFilter::Info);
    let request_engine = Arc::new(
        CloudRequestEngine::builder()
            .resource_key("test-resource-key")
            .http_client(Arc::new(DataDownCloud))
            .build()
            .expect("request engine builds"),
    );
    let fodid_engine = FodIdCloudEngine::builder()
        .cloud_request_engine(Arc::clone(&request_engine))
        .build()
        .expect("identifier engine builds");
    let pipeline = Pipeline::builder()
        .add_element(request_engine)
        .add_element(Arc::new(fodid_engine))
        .suppress_process_exceptions(true)
        .build()
        .expect("pipeline builds");
    let evidence = Evidence::builder()
        .add("header.user-agent", "Mozilla/5.0")
        .build();
    let mut data = pipeline.create_flow_data_with(evidence);
    data.process().expect("errors are suppressed");

    let logged = std::mem::take(&mut *LOGGED.lock().unwrap());
    let expected = (
        "fiftyone_fodid_cloud::engine".to_owned(),
        "INFO The 'FodIdCloudEngine' did not process as the JSON response from the \
         CloudRequestEngine was null or empty. Please refer to errors generated by the \
         CloudRequestEngine in the logs as this indicates an error occurred there."
            .to_owned(),
    );
    assert!(logged.contains(&expected), "{logged:?}");
}
