//! What the IP Intelligence cloud engine does when the cloud request fails,
//! as .NET's cloud aspect engines do. Kept in its own test binary because a
//! logger is installed once for the whole process, and each test holds
//! [`SERIAL`] so the records it reads are its own.

use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Mutex, MutexGuard};

use fiftyone_cloud_request_engine::{
    CloudHttpClient, CloudHttpRequest, CloudHttpResponse, CloudRequestEngine,
};
use fiftyone_ip_intelligence_cloud::{IpIntelligenceCloudEngine, IpIntelligenceData, IP_DATA_KEY};
use fiftyone_pipeline_core::{
    ElementData, Error, Evidence, FlowData, MissingPropertyReason, Pipeline,
};
use fiftyone_pipeline_engines::AspectEngine;

const IP_PRODUCT: &str = r#""ip":{"DataTier":"CloudV4","Properties":[
    {"Name":"RegisteredName","Type":"String","Category":"Network"}]}"#;

/// The data key of the cloud request engine's own data.
const CLOUD_KEY: &str = "cloud-response";

/// .NET's description for a property of data from a failed cloud request.
const REGISTERED_NAME_FAILED: &str = "Property 'RegisteredName' not found in data for element \
     'ip'. This is because an upstream cloud request failed, so no data was available to \
     populate the property.";

/// The record of each read of a property of data from a failed cloud request.
const REGISTERED_NAME_READ: &str = "INFO Property 'RegisteredName' missing from aspect data \
     'IpIntelligenceDataBase' because the upstream cloud request failed for this request \
     (CloudRequestFailed). See FlowData::errors for details.";

/// The info record .NET's cloud aspect engines log when they did not process.
const NOT_PROCESSED_LOG: &str = "INFO The 'IpIntelligenceCloudEngine' did not process as the \
     JSON response from the CloudRequestEngine was null or empty. Please refer to errors \
     generated by the CloudRequestEngine in the logs as this indicates an error occurred \
     there.";

/// The error .NET's cloud aspect engines record when they did not process.
const NOT_PROCESSED: &str = "pipeline error: The 'IpIntelligenceCloudEngine' did not process \
     because the JSON response from the CloudRequestEngine was null or empty. This \
     indicates that the cloud request failed.";

/// Records at info level or above from the cloud crates and the aspect data,
/// as "LEVEL message".
static LOGGED: Mutex<Vec<String>> = Mutex::new(Vec::new());

/// Held by each test for its whole run.
static SERIAL: Mutex<()> = Mutex::new(());

struct TestLogger;

impl log::Log for TestLogger {
    fn enabled(&self, metadata: &log::Metadata) -> bool {
        let target = metadata.target();
        metadata.level() <= log::Level::Info
            && (target.starts_with("fiftyone_cloud_request_engine")
                || target.starts_with("fiftyone_pipeline_core")
                || target.starts_with("fiftyone_ip_intelligence")
                || target.starts_with("fiftyone_pipeline_engines"))
    }

    fn log(&self, record: &log::Record) {
        if self.enabled(record.metadata()) {
            LOGGED
                .lock()
                .unwrap()
                .push(format!("{} {}", record.level(), record.args()));
        }
    }

    fn flush(&self) {}
}

static LOGGER: TestLogger = TestLogger;

/// Install the logger, wait for any other test to finish and clear the
/// records it left.
fn start() -> MutexGuard<'static, ()> {
    let _ = log::set_logger(&LOGGER);
    log::set_max_level(log::LevelFilter::Info);
    let guard = SERIAL
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner());
    LOGGED.lock().unwrap().clear();
    guard
}

/// Take the records logged since [`start`] or the last call.
fn take_logged() -> Vec<String> {
    std::mem::take(&mut *LOGGED.lock().unwrap())
}

/// A fake cloud granting the IP product and answering every data request
/// with `data`, or with a server error when `data_down` is set. While
/// `properties_down` is set the accessible properties request cannot reach
/// it.
struct FakeCloud {
    data: &'static str,
    data_down: bool,
    properties_down: Arc<AtomicBool>,
}

impl CloudHttpClient for FakeCloud {
    fn send(&self, request: &CloudHttpRequest) -> Result<CloudHttpResponse, String> {
        let (status, body) = if request.url.contains("accessibleproperties") {
            if self.properties_down.load(Ordering::Relaxed) {
                return Err("connection refused".to_owned());
            }
            (200, format!(r#"{{"Products":{{{IP_PRODUCT}}}}}"#))
        } else if request.url.contains("evidencekeys") {
            (200, r#"["query.client-ip"]"#.to_owned())
        } else if self.data_down {
            (500, r#"{"errors":["the service failed"]}"#.to_owned())
        } else {
            (200, self.data.to_owned())
        };
        Ok(CloudHttpResponse {
            status,
            body,
            retry_after: None,
        })
    }
}

/// The request engine and the IP Intelligence engine on a fake cloud.
fn engines(
    data: &'static str,
    data_down: bool,
    properties_down: Arc<AtomicBool>,
) -> (Arc<CloudRequestEngine>, Arc<IpIntelligenceCloudEngine>) {
    let request = Arc::new(
        CloudRequestEngine::builder()
            .resource_key("test-resource-key")
            .endpoint("https://cloud.example.test/api/v4/")
            .http_client(Arc::new(FakeCloud {
                data,
                data_down,
                properties_down,
            }))
            .build()
            .unwrap(),
    );
    let engine = IpIntelligenceCloudEngine::builder()
        .cloud_request_engine(Arc::clone(&request))
        .build()
        .unwrap();
    (request, Arc::new(engine))
}

fn pipeline(
    request: Arc<CloudRequestEngine>,
    engine: Arc<IpIntelligenceCloudEngine>,
    suppress: bool,
) -> Arc<Pipeline> {
    Pipeline::builder()
        .add_element(request)
        .add_element(engine)
        .suppress_process_exceptions(suppress)
        .build()
        .unwrap()
}

fn process(pipeline: &Arc<Pipeline>) -> (FlowData, Option<Error>) {
    let evidence = Evidence::builder()
        .add("query.client-ip", "1.1.1.1")
        .build();
    let mut data = pipeline.create_flow_data_with(evidence);
    let error = data.process().err();
    (data, error)
}

#[test]
fn a_failed_request_gives_ip_data_that_says_why() {
    let _serial = start();
    let (request, engine) = engines("{}", true, Arc::default());
    let pipeline = pipeline(request, engine, false);
    take_logged();

    let (data, error) = process(&pipeline);
    match error {
        Some(Error::Aggregate(errors)) => {
            let keys: Vec<&str> = errors
                .iter()
                .map(|error| error.element_data_key.as_str())
                .collect();
            assert_eq!(keys, vec![CLOUD_KEY], "only the request engine's error");
        }
        other => panic!("expected the request engine's error, got {other:?}"),
    }
    let recorded: Vec<(&str, bool)> = data
        .errors()
        .iter()
        .map(|error| (error.element_data_key.as_str(), error.should_throw))
        .collect();
    assert_eq!(recorded, vec![(CLOUD_KEY, true), ("ip", false)]);
    assert_eq!(data.errors()[1].source.to_string(), NOT_PROCESSED);
    let logged = take_logged();
    assert!(logged.contains(&NOT_PROCESSED_LOG.to_owned()), "{logged:?}");
    let errors: Vec<&String> = logged
        .iter()
        .filter(|record| record.starts_with("ERROR "))
        .collect();
    assert_eq!(
        errors.len(),
        1,
        "only the request engine's error: {logged:?}"
    );
    assert!(
        errors[0].starts_with(&format!(
            "ERROR An error occurred in element '{CLOUD_KEY}': "
        )),
        "{logged:?}"
    );

    let ip = data.get(IP_DATA_KEY).expect("the IP data is there");
    assert!(ip.base().cloud_request_failed());
    assert!(!ip.has_property("RegisteredName"));
    assert_eq!(
        ip.base()
            .missing_property_reason("RegisteredName")
            .unwrap()
            .reason,
        MissingPropertyReason::CloudRequestFailed
    );
    assert_eq!(take_logged(), Vec::<String>::new(), "asking logs nothing");

    // Each read logs at info level, not warning, as .NET does.
    let registered_name = ip.registered_name();
    assert!(!registered_name.has_value());
    assert_eq!(
        registered_name.no_value_message(),
        Some(REGISTERED_NAME_FAILED)
    );
    assert_eq!(
        ip.get("RegisteredName").unwrap_err().message,
        REGISTERED_NAME_FAILED
    );
    assert_eq!(
        take_logged(),
        vec![REGISTERED_NAME_READ, REGISTERED_NAME_READ]
    );
}

#[test]
fn a_failed_request_fails_nothing_more_when_errors_are_suppressed() {
    let _serial = start();
    let (request, engine) = engines("{}", true, Arc::default());
    let pipeline = pipeline(request, engine, true);
    let (data, error) = process(&pipeline);
    assert!(error.is_none(), "{error:?}");
    assert_eq!(data.errors().len(), 2);
    let logged = take_logged();
    assert!(
        !logged.iter().any(|record| record.starts_with("ERROR ")),
        "{logged:?}"
    );
    assert!(data.get(IP_DATA_KEY).unwrap().base().cloud_request_failed());
}

#[test]
fn a_successful_request_is_unchanged() {
    let _serial = start();
    let (request, engine) = engines(
        r#"{"ip":{"registeredname":"Example"}}"#,
        false,
        Arc::default(),
    );
    let pipeline = pipeline(request, engine, false);
    take_logged();
    let (data, error) = process(&pipeline);
    assert!(error.is_none(), "{error:?}");
    assert!(data.errors().is_empty());
    let ip = data.get(IP_DATA_KEY).unwrap();
    assert!(!ip.base().cloud_request_failed());
    assert!(ip.has_property("RegisteredName"));
    assert_eq!(take_logged(), Vec::<String>::new());
}

/// A cloud engine with no metadata because its property list request failed
/// gives `CloudRequestFailed`, typed accessor or not, as step 3.2 of "Deciding
/// the reason" in the properties specification says.
#[test]
fn while_the_property_list_request_has_failed_a_missing_property_says_so() {
    let _serial = start();
    let down = Arc::new(AtomicBool::new(true));
    let (request, engine) = engines(r#"{"ip":{}}"#, false, Arc::clone(&down));
    assert!(!engine.has_loaded_properties());
    assert!(engine.property_list_request_failed());

    let registered_name = engine.missing_property_reason("RegisteredName");
    assert_eq!(
        registered_name.reason,
        MissingPropertyReason::CloudRequestFailed
    );
    assert_eq!(registered_name.description, REGISTERED_NAME_FAILED);
    assert_eq!(
        engine.missing_property_reason("NotAProperty").reason,
        MissingPropertyReason::CloudRequestFailed
    );

    // Once discovery completes, the key's properties decide.
    down.store(false, Ordering::Relaxed);
    let pipeline = pipeline(request, engine.clone(), false);
    let (_data, error) = process(&pipeline);
    assert!(error.is_none(), "{error:?}");
    assert_eq!(
        engine.missing_property_reason("Town").reason,
        MissingPropertyReason::PropertyNotAccessibleWithResourceKey
    );
    assert!(engine.has_loaded_properties());
    assert!(!engine.property_list_request_failed());
}
